"""Shared loader for the native libraries that Numba loads by their names.

Numba loads some native libraries, such as TBB and SVML, by their names using the default library search path
of the operating system. However, the PyPI packages of these libraries install them in directories
that are not on the default search path of the dynamic loader,
such as the ``lib`` directory of the Python environment (``Library/bin`` on Windows), or the directory of the package.
Therefore, :class:`NativeLibrary` loads a library by its absolute path, so that the dynamic loader
then finds the already-loaded library by its name when Numba loads it.

https://github.com/numba/numba/issues/7531
"""
# https://github.com/numba/numba/issues/7531#issuecomment-1614510255

from ctypes import CDLL, DEFAULT_MODE, RTLD_GLOBAL
import importlib.metadata
import logging
import os
from pathlib import Path
import sys

from pttools.utils.system import IS_LINUX, IS_OSX, IS_WINDOWS, IS_X86_64

__all__ = ["NativeLibrary", "library_dirs"]

logger: logging.Logger = logging.getLogger(__name__)


class NativeLibrary:
    """A native library that Numba loads by its name, and which may be installed outside the default search path.

    The library is searched for first from the default search path of the operating system,
    then from the directories where the given PyPI packages have installed it,
    and finally from the library directories of the Python environment given by :func:`library_dirs`.

    Subclasses can override :meth:`get_version` to check the version of the library.
    """

    def __init__(
            self,
            name: str,
            file_names: dict[str, str],
            packages: tuple[str, ...],
            dependencies: dict[str, tuple[str, ...]] | None = None,
            global_symbols: bool = False,
            min_version: int | None = None,
            not_found_note: str = "",
            required_on_x86_64: bool = True) -> None:
        """Describe a native library. The library is loaded only by :meth:`load`.

        :param name: display name of the library, e.g. ``"TBB"``
        :param file_names: file names of the library for each operating system,
            with the keys ``"linux"``, ``"darwin"`` and ``"win32"``
        :param packages: names of the PyPI packages that provide the library
        :param dependencies: file names of the libraries that the library depends on, for each operating system.
            They are loaded from the same directory before the library itself,
            as the dynamic loader would not find them from there.
        :param global_symbols: whether to make the symbols of the library available for the libraries loaded later,
            i.e. ``RTLD_GLOBAL`` on Linux and macOS.
            This is required if the code generated by LLVM calls the functions of the library.
        :param min_version: minimum version of the library required by Numba.
            Requires that :meth:`get_version` is implemented.
        :param not_found_note: note that is logged if the library is not found, e.g. on its effects
        :param required_on_x86_64: whether the library is required on x86-64 by :meth:`check`
            even if none of its PyPI packages is installed,
            as the ``performance`` extra of PTtools installs it on x86-64 on all operating systems
        """
        self.name: str = name
        self.file_name: str | None = file_names.get(_os_key())
        self.packages: tuple[str, ...] = packages
        self.dependencies: tuple[str, ...] = (dependencies or {}).get(_os_key(), ())
        self.mode: int = RTLD_GLOBAL if global_symbols else DEFAULT_MODE
        self.min_version: int | None = min_version
        self.not_found_note: str = not_found_note
        self.required_on_x86_64: bool = required_on_x86_64

        #: The loaded library, or None if it has not been loaded
        self.library: CDLL | None = None
        #: Directory of the loaded library, or None if it was loaded from the default search path or not at all
        self.path: Path | None = None
        #: Version of the found library, or None if it was not found or has no version.
        #: This is set also if the found library was too old.
        self.version: int | None = None
        # References to the loaded dependencies are kept so that they stay loaded for the lifetime of the process.
        self._dependencies: list[CDLL] = []

    @property
    def loaded(self) -> bool:
        """Whether the library has been loaded and is compatible with Numba."""
        return self.library is not None

    def check(self) -> int:
        """Print the state of the library, and return the exit code for its check.

        :return: 0 if the library has been loaded or is not required, and 1 otherwise
        """
        if self.min_version is None:
            print(f"{self.name} loaded: {self.loaded}")
        else:
            print(f"{self.name} version: {self.version}")
        if self.path is not None:
            print(f"{self.name} directory: {self.path}")
        if self.loaded:
            return 0
        if self.required:
            return 1
        print(
            f"Note: {self.name} is not required, as none of the packages {', '.join(self.packages)} "
            "is installed and the CPU architecture is not x86-64."
        )
        return 0

    def get_version(self, library: CDLL) -> int | None:  # noqa: ARG002
        """Get the version of the loaded library.

        :param library: the loaded library
        :return: the version of the library, or None if the library has no version
        """
        return None

    def installed_packages(self) -> list[str]:
        """The PyPI packages providing the library that are installed."""
        installed = []
        for package in self.packages:
            try:
                importlib.metadata.distribution(package)
            except importlib.metadata.PackageNotFoundError:
                continue
            installed.append(package)
        return installed

    def load(self) -> bool:
        """Load the library, if it's found and compatible with Numba.

        :return: whether the library was loaded
        """
        if self.loaded:
            return True
        if self.file_name is None:
            logger.warning("Cannot load %s on an unknown operating system.", self.name)
            return False

        try:
            if self._try_load(self.load_from()):
                return True
        except OSError:
            pass
        else:
            logger.warning(
                "The %s found from the default library search path is too old for Numba: %s < %s. "
                "Trying the directories of the Python environment.",
                self.name, self.version, self.min_version
            )
        system_version = self.version

        for lib_dir in self.search_dirs():
            try:
                if self._try_load(self.load_from(lib_dir), lib_dir):
                    logger.debug("Loaded %s from %s", self.name, lib_dir)
                    return True
            except OSError as e:
                logger.warning("Failed to load %s from %s: %s", self.name, lib_dir, e)
                continue
            logger.warning(
                "The %s library at %s is too old for Numba: %s < %s.",
                self.name, lib_dir, self.version, self.min_version
            )

        self.version = system_version
        if system_version is None:
            logger.info(
                "%s was not found.%s "
                "You can install it with the \"performance\" extra of PTtools, if it's available for your platform.",
                self.name, f" {self.not_found_note}" if self.not_found_note else ""
            )
        else:
            logger.error(
                "The installed %s is too old for Numba: %s < %s. "
                "Please install a newer version, e.g. with the \"performance\" extra of PTtools.",
                self.name, system_version, self.min_version
            )
        return False

    def load_from(self, path: str | os.PathLike[str] | None = None) -> CDLL:
        """Load the library and its dependencies from the given directory, or from the default search path.

        This does not check the version of the library, or store it as the loaded library.

        :param path: directory of the library. If not given, the default search path of the operating system is used.
        :return: the loaded library
        :raises OSError: if the library or one of its dependencies cannot be loaded
        """
        if self.file_name is None:
            raise OSError(f"Cannot load {self.name} on an unknown operating system.")
        if path is None:
            return CDLL(self.file_name, mode=self.mode)
        # sys.platform is checked instead of IS_WINDOWS, as type checkers use it to know that the function exists.
        if sys.platform == "win32":
            # Allow the loader to find the dependencies of the library, and the library itself when Numba loads it.
            os.add_dll_directory(path)
        for dependency in self.dependencies:
            self._dependencies.append(CDLL(Path(path) / dependency, mode=self.mode))
        return CDLL(Path(path) / self.file_name, mode=self.mode)

    @property
    def required(self) -> bool:
        """Whether the library is required by :meth:`check`.

        This is the case if one of its PyPI packages is installed,
        or if the CPU architecture is x86-64 and the library is required there.
        """
        return (IS_X86_64 and self.required_on_x86_64) or bool(self.installed_packages())

    def search_dirs(self) -> list[Path]:
        """Directories of the Python environment that contain the library, in the order in which they are tried.

        These are first the directories where the PyPI packages of the library have installed it,
        and then the library directories of the Python environment given by :func:`library_dirs`.
        """
        if self.file_name is None:
            return []
        dirs: list[Path] = []
        for package in self.packages:
            try:
                files = importlib.metadata.files(package)
            except importlib.metadata.PackageNotFoundError:
                continue
            for file in files or []:
                if file.name == self.file_name:
                    candidate = Path(file.locate()).resolve().parent
                    if candidate not in dirs:
                        dirs.append(candidate)
        for candidate in library_dirs():
            if candidate not in dirs and (candidate / self.file_name).is_file():
                dirs.append(candidate)
        return dirs

    def _try_load(self, library: CDLL, path: Path | None = None) -> bool:
        """Store the library as the loaded library if it's compatible with Numba."""
        self.version = self.get_version(library)
        if self.min_version is not None and (self.version is None or self.version < self.min_version):
            return False
        self.library = library
        self.path = path
        return True


def library_dirs() -> list[Path]:
    """Library directories of the Python environment.

    These are the ``lib`` directories (``Library/bin`` and ``bin`` on Windows) of the current virtual environment
    and its base interpreter, where e.g. the ``tbb`` and ``intel-cmplr-lib-rt`` packages from PyPI
    install their libraries.
    """
    prefixes = [sys.prefix, sys.base_prefix]
    venv = os.getenv("VIRTUAL_ENV")
    if venv:
        prefixes.append(venv)

    dirs: list[Path] = []
    for prefix in prefixes:
        prefix_path = Path(prefix)
        candidates = [prefix_path / "Library" / "bin", prefix_path / "bin"] if IS_WINDOWS else [prefix_path / "lib"]
        for candidate in candidates:
            if candidate not in dirs and candidate.is_dir():
                dirs.append(candidate)
    return dirs


def _os_key() -> str:
    if IS_WINDOWS:
        return "win32"
    if IS_OSX:
        return "darwin"
    if IS_LINUX:
        return "linux"
    return sys.platform
