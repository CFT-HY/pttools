"""A fix for loading Intel Short Vector Math Library (SVML) for Numba.

Numba loads the SVML library by its name when it's imported,
and uses it for vectorizing math functions if llvmlite has been built with the SVML patch of LLVM.
The ``intel-cmplr-lib-rt`` package from PyPI (``icc-rt`` on macOS) installs the library
in the ``lib`` directory of the Python environment (``Library/bin`` on Windows),
which is not on the default search path of the dynamic loader.
Therefore, this module loads the library by its absolute path, as explained in
:mod:`pttools.speedup.libraries.library`.
Unlike TBB, this has to be done before Numba is imported,
which is why :mod:`pttools.speedup` imports this module first.

However, as of llvmlite 0.45 (LLVM 20), the llvmlite wheels from PyPI are built without the SVML patch,
so Numba cannot use SVML even if the library is loaded.
https://llvmlite.readthedocs.io/en/stable/user-guide/llvm20.html
https://github.com/numba/llvmlite/issues/1441#issuecomment-4752332762
"""

import logging
import sys

from pttools.speedup.libraries.library import NativeLibrary

__all__ = ["SVML", "SVML_LOADED", "SVMLLibrary", "llvmlite_has_svml", "numba_uses_svml"]

logger: logging.Logger = logging.getLogger(__name__)


class SVMLLibrary(NativeLibrary):
    """The SVML library, whose state in Numba is printed by :meth:`check`."""

    def check(self) -> int:
        """Print the state of SVML in llvmlite and Numba in addition to that of the library."""
        returncode = super().check()
        has_svml = llvmlite_has_svml()
        print("llvmlite built with SVML:", has_svml)
        print("Numba uses SVML:", numba_uses_svml())
        if self.loaded and not has_svml:
            print(
                "Note: Numba cannot use SVML, as llvmlite has been built without the SVML patch of LLVM. "
                "This is the case for the llvmlite wheels from PyPI as of llvmlite 0.45."
            )
        return returncode

    def load(self) -> bool:
        """Load the SVML library, and warn if it was too late for Numba to use it."""
        numba_imported = "numba" in sys.modules
        loaded = super().load()
        if loaded and numba_imported and llvmlite_has_svml() and not numba_uses_svml():
            logger.warning(
                "SVML was loaded after Numba was imported, so Numba does not use it. "
                "Please import PTtools before Numba."
            )
        return loaded


#: The SVML library
SVML: SVMLLibrary = SVMLLibrary(
    name="SVML",
    file_names={"linux": "libsvml.so", "darwin": "libsvml.dylib", "win32": "svml_dispmd.dll"},
    packages=("intel-cmplr-lib-rt", "icc-rt"),
    # libintlc has to be loaded first, as it's not found from the directory of libsvml.
    dependencies={"linux": ("libintlc.so.5",), "darwin": ("libintlc.dylib",)},
    # The code generated by LLVM calls the functions of SVML.
    global_symbols=True,
    not_found_note="Numba will not use SVML for vectorizing math functions.",
)


def llvmlite_has_svml() -> bool:
    """Whether llvmlite has been built with the SVML patch of LLVM, which is required for Numba to use SVML."""
    import llvmlite.binding  # noqa: PLC0415

    has_svml = getattr(llvmlite.binding.targets, "has_svml", None)
    return bool(has_svml()) if has_svml is not None else False


def numba_uses_svml() -> bool:
    """Whether Numba uses SVML, i.e. ``numba.config.USING_SVML``.

    This imports Numba, so it should not be called before :data:`SVML` has been loaded.
    """
    from numba.core import config  # noqa: PLC0415

    return bool(getattr(config, "USING_SVML", False))


#: Whether the SVML library was loaded when this module was imported.
#: The library is loaded on import, so that it's loaded before Numba is imported.
SVML_LOADED: bool = SVML.load()
